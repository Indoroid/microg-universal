#!/usr/bin/env python3
"""
Generates MicroGConstants.kt for the universal microG patch.

Source of truth = what MicroG-RE actually answers on under its own prefix:
every action / permission / provider authority that its manifests declare as
"${basePackageName}.<suffix>" is renamed com.google.<suffix> -> <vendor>.<suffix>.
meta-data keys (e.g. com.google.android.gms.version) are deliberately excluded:
clients read those from their *own* manifest.

Optional: --gmscore <GmsCore.apk> reports names GmsCore exports that MicroG-RE
does not implement (left untouched by the patch).

usage: gen_constants.py <MicroG-RE dir> <out.kt> [--gmscore GmsCore.apk]
"""
import argparse
import pathlib
import re
import xml.etree.ElementTree as ET

A = "{http://schemas.android.com/apk/res/android}"
PH = "${basePackageName}"
# Must stay com.google.*: read from the client's own manifest or used as class / module ids.
NEVER_RENAME = {
    "com.google.android.gms.version",
    "com.google.android.gms.policy_cast_dynamite",
}


def collect_microg(root: pathlib.Path):
    actions, permissions, authorities = set(), set(), set()
    for mf in root.rglob("AndroidManifest.xml"):
        if "/build/" in str(mf):
            continue
        text = mf.read_text(encoding="utf-8")
        if PH not in text:
            continue
        tree = ET.fromstring(text)
        for el in tree.iter():
            tag = el.tag
            for attr, val in el.attrib.items():
                if PH not in val:
                    continue
                for v in val.split(";"):
                    if not v.startswith(PH):
                        continue
                    name = "com.google" + v[len(PH):]
                    if tag == "meta-data" or name in NEVER_RENAME:
                        continue
                    if attr == A + "authorities":
                        authorities.add(name)
                    elif tag == "action" and attr == A + "name":
                        actions.add(name)
                    elif (tag in ("permission", "uses-permission") and attr == A + "name") or attr.endswith("permission"):
                        permissions.add(name)
    # Package itself is handled separately (exact match).
    for s in (actions, permissions, authorities):
        s.discard("com.google.android.gms")
    return actions, permissions, authorities


def collect_gmscore(apk_path):
    from loguru import logger
    logger.remove()
    from androguard.core.apk import APK
    apk = APK(apk_path)
    xml = apk.get_android_manifest_xml()
    acts, perms, auths = set(), set(), set()
    for el in xml.iter():
        for attr, val in el.attrib.items():
            if el.tag == "action" and attr == A + "name":
                acts.add(val)
            elif el.tag == "permission" and attr == A + "name":
                perms.add(val)
            elif attr == A + "authorities":
                auths.update(val.split(";"))
    return acts, perms, auths


def kt_set(name, values):
    body = "\n".join(f'        "{v}",' for v in sorted(values))
    return f"    val {name} = setOf(\n{body}\n    )\n"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("microg")
    p.add_argument("out")
    p.add_argument("--gmscore")
    a = p.parse_args()
    acts, perms, auths = collect_microg(pathlib.Path(a.microg))
    note = ""
    if a.gmscore:
        gacts, gperms, gauths = collect_gmscore(a.gmscore)
        gms_like = re.compile(r"^com\.google\.")
        missing = sorted(x for x in (gacts | gperms) if gms_like.match(x) and x not in acts | perms)
        extra = sorted(x for x in acts | perms | auths if x not in gacts | gperms | gauths)
        print(f"GmsCore exports {len(gacts)} actions / {len(gperms)} permissions / {len(gauths)} authorities")
        print(f"not implemented by MicroG-RE (left as-is): {len(missing)}")
        print(f"MicroG-RE names absent in GmsCore manifest (kept; often client-side names): {len(extra)}")
        note = (f" * Cross-checked with GmsCore manifest: {len(missing)} GmsCore names not implemented by MicroG-RE\n"
                f" * are intentionally not renamed.\n")
    out = (
        "// GENERATED by tools/gen_constants.py from MicroG-RE manifests. Do not edit by hand.\n"
        "package app.morphe.patches.all.misc.microg\n\n"
        "/**\n * Names MicroG-RE serves under its own vendor prefix (com.google.X -> <vendor>.X).\n"
        f"{note} */\n"
        "internal object MicroGConstants {\n"
        + kt_set("ACTIONS", acts) + "\n"
        + kt_set("PERMISSIONS", perms) + "\n"
        + kt_set("AUTHORITIES", auths)
        + "}\n"
    )
    pathlib.Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(a.out).write_text(out)
    print(f"wrote {a.out}: {len(acts)} actions, {len(perms)} permissions, {len(auths)} authorities")


if __name__ == "__main__":
    main()
